const orderedSourceMessages = Object.entries(sourceMessages).sort(
  ([left], [right]) => right.length - left.length,
)

export function translateSourceMessage(value: string): string {
  let translated = value
  for (const [source, target] of orderedSourceMessages) {
    if (translated.includes(source)) translated = translated.split(source).join(target)
  }
  return translated
}

export function translateExactSourceMessage(value: string): string {
  const leading = value.match(/^\s*/)?.[0] ?? ''
  const trailing = value.match(/\s*$/)?.[0] ?? ''
  const content = value.slice(leading.length, value.length - trailing.length)
  const translated = sourceMessages[content]
  return translated ? `${leading}${translated}${trailing}` : value
}
